def format_elevation(meters: float) -> str:
    """标高数值格式化：±0.000 / 3.000 / -0.450（三位小数，单位米）。"""
    if abs(meters) < 1e-9:
        return "\u00b10.000"
    s = f"{abs(meters):.3f}"
    return s if meters > 0 else "-" + s
