# DXF lineweight 合法值（1/100 mm），用于校验
DXF_LINEWEIGHTS = (0, 5, 9, 13, 15, 18, 20, 25, 30, 35, 40, 50, 53, 60, 70,
                   80, 90, 100, 106, 120, 140, 158, 200, 211)


def to_dxf_lineweight(mm: float) -> int:
    """把线宽(mm)转换为 DXF 的 1/100mm 整数值，吸附到最近的合法档位。

    线宽只允许国标四档：b / 0.7b / 0.5b / 0.25b。
    b=0.5 组下的换算：0.25b=0.125→13、0.5b=0.25→25、0.7b=0.35→35、b=0.5→50。
    这四档在 DXF 合法值里**逐档一一对应**，用「取最近值」即可；
    不要改成「向上吸附」，那会把 0.25b 抬到 25 与 0.5b 撞档。
    粗:中粗:中:细 = 4:3:2:1，层次不能丢。
    """
    raw = int(round(mm * 100))
    return min(DXF_LINEWEIGHTS, key=lambda v: abs(v - raw))


